<?php

declare(strict_types=1);

use App\Support\Money;
use App\Support\ProgressPercentage;

/*
|--------------------------------------------------------------------------
| عرض المبالغ ونسبة التقدّم دون float (T06 — docs/SPEC.md §7)
|--------------------------------------------------------------------------
*/

test('يعرض المبلغ بفواصل الآلاف ويحذف الهللات الصفرية', function (string $amount, string $expected): void {
    expect(Money::format($amount))->toBe($expected);
})->with([
    'بلا هللات' => ['50000.00', '50,000 ر.س'],
    'بهللات' => ['1250.50', '1,250.50 ر.س'],
    'أقل من ألف' => ['999.00', '999 ر.س'],
    'صفر' => ['0.00', '0 ر.س'],
    'الحد الأعلى' => ['9999999999.99', '9,999,999,999.99 ر.س'],
]);

test('نسبة التقدّم عدد صحيح يُقرَّب للأدنى ولا يتجاوز 100', function (string $collected, string $target, int $expected): void {
    expect(ProgressPercentage::of($collected, $target))->toBe($expected);
})->with([
    'لا شيء' => ['0', '50000.00', 0],
    'أقل من النصف بقليل' => ['24999.99', '50000.00', 49],
    'قبيل الاكتمال لا تظهر 100' => ['49999.99', '50000.00', 99],
    'الاكتمال' => ['50000.00', '50000.00', 100],
    'التجاوز يبقى 100' => ['60000.00', '50000.00', 100],
    'مستهدف صفري' => ['100.00', '0.00', 0],
]);
